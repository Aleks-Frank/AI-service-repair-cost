"""Чек-лист обязательных материалов по виду работы (EXP-C6).

Воронка EXP-C1: из 16 материалов мастера модель запросила 3, а всё запрошенное поиск по прайсам
нашёл. Значит, материалы теряются не в поиске, а в том, что модель их не называет. Нехватка
материала хуже лишнего (замечание на защите 3 спринта): работа останавливается.

Правило: если для работы данного вида модель не запросила обязательный материал (ни один запрос
не похож на него), код добавляет потребность сам. Виды работ задаются по наименованию расценки ПЗР,
а не по коду, и описывают общую практику, а не конкретные заявки: хомутом заделывают свищ,
резьбовое соединение уплотняют пастой и льном, при смене светильника нужен светильник.
Проверка — на тех же 10 АВР, по которым видны пропуски, поэтому прирост там — оценка сверху.

Добавленные потребности проходят обычный подбор товаров и проверку «работа ↔ материал»; в смете
у них reason «чек-лист по виду работы».
"""

import re
from decimal import Decimal

# (вид работы — регулярка по наименованию, [(запрос, похожие запросы — регулярка, на ед. работы, ед., расходник)])
CHECKLIST: list[tuple[str, list[tuple[str, str, str, str, bool]]]] = [
    # Временная заделка свища — хомут и резиновая прокладка под него.
    (r"временная заделка свищей",
     [("хомут ремонтный для трубы", r"хомут", "1", "шт", False),
      ("пластина резиновая техническая", r"пластин|резин|прокладк", "0.1", "кг", True)]),
    # Резьбовые соединения водопровода (кран, муфтовая арматура, сгон, фильтр): уплотнение пастой и льном.
    # 0,25 упаковки на соединение: одной упаковки хватает на 4 соединения (покупка округляется вверх).
    (r"муфтовой арматуры|сгон|фильтров грубой очистки|смена кранов",
     [("паста уплотнительная сантехническая", r"паст|герметик|уплотн", "0.25", "шт", True),
      ("лён сантехнический", r"л[её]н|пакл|нить|фум", "0.25", "шт", True)]),
    # Установка муфтовой арматуры — сам кран.
    (r"установка муфтовой арматуры",
     [("кран шаровый латунный муфтовый", r"кран", "1", "шт", False)]),
    # Смена/установка светильника — светильник (если модель не запросила).
    (r"^(смена|установка) светильник",
     [("светильник светодиодный", r"светильник|прожектор|фонар", "1", "шт", False)]),
]
_COMPILED = [(re.compile(work, re.IGNORECASE),
              [(query, re.compile(similar, re.IGNORECASE), qty, unit, consumable)
               for query, similar, qty, unit, consumable in items])
             for work, items in CHECKLIST]
REASON = "чек-лист по виду работы"


def add_checklist_needs(needs: list[dict], works: list[dict]) -> list[dict]:
    """Дополняет потребности обязательными материалами по виду каждой работы основной сметы.

    Принимает:
        needs — потребности из materials.collect_needs (изменяется на месте: добавляются новые);
        works — основные строки сметы (make_estimate): work_id, finding_id, name, unit, quantity.
    Возвращает: список добавленных потребностей (для трассировки).
    """
    added = []
    for line in works:
        own = [n["query"] for n in needs if (n["finding_id"], n["work_id"]) == (line["finding_id"], line["work_id"])]
        for pattern, items in _COMPILED:
            if not pattern.search(line["name"]):
                continue
            for query, similar, qty, unit, consumable in items:
                if any(similar.search(q) for q in own):
                    continue
                need = {
                    "need_id": f"m{len(needs) + 1}",
                    "finding_id": line["finding_id"],
                    "work_id": line["work_id"],
                    "work_name": line["name"],
                    "work_unit": line["unit"],
                    "work_quantity": line["quantity"],
                    "query": query,
                    "qty_per_work_unit": str(Decimal(qty)),
                    "unit": unit,
                    "consumable": consumable,
                    "reason": REASON,
                }
                needs.append(need)
                own.append(query)
                added.append(need)
    return added
